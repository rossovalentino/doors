/// The subsystem of Windows program `name` (lower case, no `.exe`).
pub fn subsystem(name: &str) -> Option<u8> {
    PROGRAMS
        .binary_search_by(|(n, _)| n.as_bytes().cmp(name.as_bytes()))
        .ok()
        .map(|i| PROGRAMS[i].1)
}
